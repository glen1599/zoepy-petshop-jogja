-- Profil admin. Satu baris per pengguna Supabase Auth.
create table if not exists public.profiles (
  id          uuid primary key references auth.users on delete cascade,
  email       text,
  full_name   text,
  is_admin    boolean not null default false,
  created_at  timestamptz not null default now()
);

create table if not exists public.services (
  id           bigint generated by default as identity primary key,
  slug         text not null unique,
  title        text not null,
  summary      text,
  tags         text[] not null default '{}',
  image_url    text,
  sort_order   int    not null default 0,
  published    boolean not null default true,
  created_at   timestamptz not null default now()
);

create table if not exists public.products (
  id             bigint generated by default as identity primary key,
  name           text not null,
  description    text,
  category       text,
  price_idr      int,
  compare_idr    int,
  image_url      text,
  badge          text,
  in_stock       boolean not null default true,
  sort_order     int     not null default 0,
  published      boolean not null default true,
  created_at     timestamptz not null default now(),
  constraint products_price_positive      check (price_idr   is null or price_idr   >= 0),
  constraint products_compare_positive    check (compare_idr is null or compare_idr >= 0)
);

create table if not exists public.testimonials (
  id          bigint generated by default as identity primary key,
  author      text not null,
  location    text,
  quote       text not null,
  rating      int  not null default 5 check (rating between 1 and 5),
  avatar_url  text,
  sort_order  int  not null default 0,
  published   boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.team_members (
  id          bigint generated by default as identity primary key,
  name        text not null,
  role        text,
  photo_url   text,
  sort_order  int  not null default 0,
  published   boolean not null default true,
  created_at  timestamptz not null default now()
);

create table if not exists public.posts (
  id            bigint generated by default as identity primary key,
  slug          text not null unique,
  title         text not null,
  excerpt       text,
  body          text,
  cover_url     text,
  category      text,
  published_at  timestamptz not null default now(),
  published     boolean not null default true,
  created_at    timestamptz not null default now()
);

-- Permintaan booking dari formulir publik.
create table if not exists public.bookings (
  id            bigint generated by default as identity primary key,
  name          text not null,
  phone         text not null,
  pet_name      text,
  pet_type      text,
  service_slug  text,
  preferred_at  timestamptz,
  notes         text,
  status        text not null default 'new'
                check (status in ('new', 'confirmed', 'done', 'cancelled')),
  created_at    timestamptz not null default now(),
  constraint bookings_name_len  check (char_length(name)  between 2 and 80),
  constraint bookings_phone_len check (char_length(phone) between 7 and 20),
  constraint bookings_notes_len check (notes is null or char_length(notes) <= 1000)
);

-- Kontak toko, jam buka, media sosial — satu baris per kunci.
create table if not exists public.site_settings (
  key         text primary key,
  value       jsonb not null,
  updated_at  timestamptz not null default now()
);

create index if not exists services_published_idx     on public.services     (published, sort_order);
create index if not exists products_published_idx     on public.products     (published, sort_order);
create index if not exists testimonials_published_idx on public.testimonials (published, sort_order);
create index if not exists team_published_idx         on public.team_members (published, sort_order);
create index if not exists posts_published_idx        on public.posts        (published, published_at desc);
create index if not exists bookings_status_idx        on public.bookings     (status, created_at desc);

-- ---------------------------------------------------------------------------
--  2. HELPER: apakah pemanggil ini admin?
--     SECURITY DEFINER supaya membaca `profiles` tanpa memicu RLS-nya sendiri
--     (kalau tidak, policy di profiles akan rekursif ke dirinya sendiri).
-- ---------------------------------------------------------------------------

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.profiles
    where id = auth.uid() and is_admin = true
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ---------------------------------------------------------------------------
--  3. TRIGGER: buat baris profil otomatis saat ada user Auth baru
-- ---------------------------------------------------------------------------

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public, pg_temp
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, new.email, coalesce(new.raw_user_meta_data->>'full_name', ''))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
--  4. ROW LEVEL SECURITY
--     Prinsipnya: pengunjung anonim hanya boleh MELIHAT konten yang
--     published = true, dan boleh MENGIRIM satu booking baru.
--     Sisanya hanya admin.
-- ---------------------------------------------------------------------------

alter table public.profiles      enable row level security;
alter table public.services      enable row level security;
alter table public.products      enable row level security;
alter table public.testimonials  enable row level security;
alter table public.team_members  enable row level security;
alter table public.posts         enable row level security;
alter table public.bookings      enable row level security;
alter table public.site_settings enable row level security;

-- profiles ------------------------------------------------------------------
drop policy if exists "profiles: read own or admin" on public.profiles;
create policy "profiles: read own or admin"
  on public.profiles for select
  using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles: admin writes" on public.profiles;
create policy "profiles: admin writes"
  on public.profiles for all
  using (public.is_admin())
  with check (public.is_admin());

-- Konten publik: pola yang sama untuk lima tabel ------------------------------
do $$
declare
  t text;
begin
  foreach t in array array['services', 'products', 'testimonials', 'team_members', 'posts']
  loop
    execute format('drop policy if exists "%s: public reads published" on public.%I', t, t);
    execute format(
      'create policy "%s: public reads published" on public.%I for select
         using (published = true or public.is_admin())', t, t);

    execute format('drop policy if exists "%s: admin inserts" on public.%I', t, t);
    execute format(
      'create policy "%s: admin inserts" on public.%I for insert
         with check (public.is_admin())', t, t);

    execute format('drop policy if exists "%s: admin updates" on public.%I', t, t);
    execute format(
      'create policy "%s: admin updates" on public.%I for update
         using (public.is_admin()) with check (public.is_admin())', t, t);

    execute format('drop policy if exists "%s: admin deletes" on public.%I', t, t);
    execute format(
      'create policy "%s: admin deletes" on public.%I for delete
         using (public.is_admin())', t, t);
  end loop;
end $$;

-- site_settings --------------------------------------------------------------
drop policy if exists "settings: public reads" on public.site_settings;
create policy "settings: public reads"
  on public.site_settings for select
  using (true);

drop policy if exists "settings: admin writes" on public.site_settings;
create policy "settings: admin writes"
  on public.site_settings for all
  using (public.is_admin())
  with check (public.is_admin());

-- bookings -------------------------------------------------------------------
-- Siapa pun boleh mengirim booking, tetapi HANYA dengan status 'new':
-- pengirim tidak boleh memalsukan status atau mengubah booking orang lain.
drop policy if exists "bookings: anyone may submit" on public.bookings;
create policy "bookings: anyone may submit"
  on public.bookings for insert
  to anon, authenticated
  with check (status = 'new');

drop policy if exists "bookings: admin reads" on public.bookings;
create policy "bookings: admin reads"
  on public.bookings for select
  using (public.is_admin());

drop policy if exists "bookings: admin updates" on public.bookings;
create policy "bookings: admin updates"
  on public.bookings for update
  using (public.is_admin())
  with check (public.is_admin());

drop policy if exists "bookings: admin deletes" on public.bookings;
create policy "bookings: admin deletes"
  on public.bookings for delete
  using (public.is_admin());

